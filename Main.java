public class Main {

    public static void main(String[] args) {

        // Vòng lặp
        for (int i = 1; i <= 10; i++) {

            // Lệnh rẽ nhánh
            if (i % 2 == 0) {
                System.out.println(i + " la so chan");
            } else {
                System.out.println(i + " la so le");
            }
        }
    }
}